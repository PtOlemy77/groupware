const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async function inspectExpenses({page,dialog,artifacts}) {
  await dialog.getByRole('button',{name:'직접경비',exact:true}).click();
  assert.equal(await dialog.getByRole('button',{name:'입금계획',exact:true}).count(),0);
  const section=dialog.getByRole('region',{name:'직접경비 산출',exact:true});
  const table=section.getByRole('table',{name:'직접경비 세부 항목',exact:true});
  assert.equal(await table.locator('tr[data-expense-code]').count(),44);
  assert.equal(await section.locator('article').count(),0);
  assert.equal(await section.getByTestId('direct-expense-total').textContent(),'0 천원');
  const meal=section.locator('[data-expense-code="OVERTIME_MEAL"]');
  assert.equal(await section.getByRole('combobox').count(),0);
  assert.equal(await table.getByRole('columnheader').count(),5);
  assert.equal(await table.locator('tbody tr').first().evaluate(node=>node.getBoundingClientRect().height<=44),true,'Each expense must fit a compact row');
  assert.equal(await meal.getByRole('spinbutton').first().evaluate(node=>getComputedStyle(node).fontSize),'14px');
  assert.equal(await section.locator('p').count(),0,'No per-row explanations');
  const mealPrice=meal.getByRole('spinbutton',{name:'복리/특근식대 기준금액',exact:true});
  assert.equal(await mealPrice.inputValue(),'10');
  assert.equal(await meal.getByRole('spinbutton',{name:'복리/특근식대 횟수',exact:true}).inputValue(),'');
  assert.equal(await section.locator('[data-expense-code="SUPPLIES_OFFICE"]').getByRole('spinbutton',{name:'소모품비/전산,사무,기타 기준금액',exact:true}).inputValue(),'15');
  assert.equal(await section.locator('[data-expense-code="TRAVEL_SENIOR"]').getByRole('spinbutton',{name:'국내출장비/부·차장 기준금액',exact:true}).inputValue(),'187.8');
  await mealPrice.fill('0');
  await section.getByRole('button',{name:'기본단가 적용',exact:true}).click();
  await page.getByRole('dialog').last().getByRole('button',{name:'취소',exact:true}).click();
  assert.equal(await mealPrice.inputValue(),'');
  await section.getByRole('button',{name:'기본단가 적용',exact:true}).click();
  await page.getByRole('dialog').last().getByRole('button',{name:'적용',exact:true}).click();
  assert.equal(await mealPrice.inputValue(),'10');
  assert.equal(await section.getByTestId('direct-expense-total').textContent(),'0 천원');
  // 입력한 0이 저장 후 기본단가로 덮어써지지 않는지 재조회 단계에서 확인한다.
  await section.locator('[data-expense-code="SW_RENT"]').getByRole('spinbutton',{name:'임차료/SW 기준금액',exact:true}).fill('0');
  await meal.getByRole('spinbutton',{name:'복리/특근식대 기준단위',exact:true}).fill('2.25');
  await meal.getByRole('spinbutton',{name:'복리/특근식대 횟수',exact:true}).fill('3');
  await meal.getByRole('spinbutton',{name:'복리/특근식대 기준금액',exact:true}).fill('10');
  assert.equal(await meal.getByLabel('복리/특근식대 산출금액',{exact:true}).textContent(),'67.5');
  const travel=section.locator('[data-expense-code="TRAVEL_SENIOR"]');
  for(const [label,value] of [['기준단위','2'],['기준금액','120'],['횟수','3']]) await travel.getByRole('spinbutton',{name:'국내출장비/부·차장 '+label,exact:true}).fill(value);
  assert.equal(await travel.getByLabel('국내출장비/부·차장 산출금액',{exact:true}).textContent(),'720');
  const insurance=section.locator('[data-expense-code="CONTRACT_INSURANCE"]');
  await insurance.getByRole('spinbutton',{name:'보증보험료(계약) 기준금액',exact:true}).fill('300');
  await insurance.getByRole('spinbutton',{name:'보증보험료(계약) 횟수',exact:true}).fill('1');
  const expected=1087.5;
  assert.equal(await section.getByTestId('direct-expense-total').textContent(),expected.toLocaleString()+' 천원');
  await section.getByRole('button',{name:'금액 초기화',exact:true}).click();
  await page.getByRole('dialog').last().getByRole('button',{name:'취소',exact:true}).click();
  assert.equal(await section.getByTestId('direct-expense-total').textContent(),expected.toLocaleString()+' 천원');
  for(const width of [390,768]) {
    await page.setViewportSize({width,height:900});
    const scroll=section.getByRole('region',{name:'직접경비 목록 가로 스크롤',exact:true});
    assert.equal(await scroll.evaluate(node=>{node.scrollLeft=node.scrollWidth;const reached=node.scrollLeft+node.clientWidth>=node.scrollWidth-1;node.scrollLeft=0;return reached;}),true);
    assert.equal(await table.getByRole('columnheader',{name:'계정과목',exact:true}).count(),1);
    assert.equal(await section.evaluate(node=>node.scrollWidth>node.clientWidth+1),false,'Expense inputs must fit '+width);
  }
  await page.setViewportSize({width:1440,height:1000});
  await meal.scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(artifacts,'direct-expense-list.png')});
  await meal.screenshot({path:path.join(artifacts,'direct-expense-meal.png')});
  await travel.screenshot({path:path.join(artifacts,'direct-expense-travel.png')});
  return expected;
};
