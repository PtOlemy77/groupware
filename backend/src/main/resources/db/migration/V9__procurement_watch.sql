-- Isolated procurement data. Existing employee/business records are not modified.
CREATE TABLE procurement_rules (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 created_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 employee_id bigint NOT NULL REFERENCES employees(id),
 name varchar(100) NOT NULL,
 keywords text NOT NULL,
 excluded_keywords text NOT NULL,
 institutions text NOT NULL,
 match_mode varchar(10) NOT NULL CHECK(match_mode IN ('AND','OR')),
 notice_kind varchar(10) NOT NULL CHECK(notice_kind IN ('ALL','BID','SPEC')),
 business_type varchar(10) NOT NULL CHECK(business_type IN ('ALL','SERVC','THNG','CNSTWK','FRGCPT')),
 enabled boolean NOT NULL DEFAULT true
);
CREATE INDEX procurement_rule_owner ON procurement_rules(employee_id,id);
CREATE TABLE procurement_notices (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 kind varchar(10) NOT NULL CHECK(kind IN ('BID','SPEC')),
 business_type varchar(10) NOT NULL,
 external_id varchar(100) NOT NULL,
 revision varchar(100) NOT NULL,
 fingerprint varchar(64) NOT NULL,
 title varchar(2000) NOT NULL,
 agency varchar(500) NOT NULL,
 demand_agency varchar(500) NOT NULL,
 agency_code varchar(100) NOT NULL,
 demand_agency_code varchar(100) NOT NULL,
 published_at varchar(50) NOT NULL,
 changed_at varchar(50) NOT NULL,
 deadline varchar(50) NOT NULL,
 budget varchar(100) NOT NULL,
 notice_status varchar(100) NOT NULL,
 source_url varchar(2000) NOT NULL,
 detected_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT procurement_notice_identity UNIQUE(kind,business_type,external_id,revision,fingerprint)
);
CREATE TABLE procurement_alerts (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 created_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 employee_id bigint NOT NULL REFERENCES employees(id),
 notice_id bigint NOT NULL REFERENCES procurement_notices(id),
 matched_rules varchar(2000) NOT NULL,
 read_on timestamptz,
 CONSTRAINT procurement_alert_once UNIQUE(employee_id,notice_id)
);
CREATE INDEX procurement_alert_owner ON procurement_alerts(employee_id,created_on DESC);
CREATE TABLE procurement_alert_rules (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alert_id bigint NOT NULL REFERENCES procurement_alerts(id),
 rule_id bigint REFERENCES procurement_rules(id) ON DELETE SET NULL,
 rule_name varchar(100) NOT NULL,
 CONSTRAINT procurement_alert_rule_once UNIQUE(alert_id,rule_id)
);
CREATE TABLE procurement_sync_state (
 id varchar(50) PRIMARY KEY,
 from_time timestamp,
 until_time timestamp,
 next_page integer NOT NULL DEFAULT 1,
 last_success timestamptz,
 last_attempt timestamptz,
 last_error varchar(300),
 lease_until timestamptz,
 lease_token varchar(100)
);
