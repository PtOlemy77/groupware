-- Additive evaluation workflow. Existing evaluations and employee records are unchanged.
CREATE TABLE evaluation_assignments (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 created_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 employee_id bigint NOT NULL REFERENCES employees(id),
 project_id bigint NOT NULL REFERENCES projects(id),
 assigned_on date NOT NULL,
 ended_on date,
 CONSTRAINT evaluation_assignment_period CHECK (ended_on IS NULL OR ended_on >= assigned_on),
 CONSTRAINT evaluation_assignment_identity UNIQUE(id, project_id, employee_id)
);
CREATE UNIQUE INDEX evaluation_assignment_active ON evaluation_assignments(project_id,employee_id) WHERE ended_on IS NULL;
CREATE INDEX evaluation_assignment_employee ON evaluation_assignments(employee_id);
INSERT INTO evaluation_assignments(employee_id,project_id,assigned_on)
SELECT x.employee_id,p.id,p.start_date FROM projects p JOIN (
 SELECT project_id,employee_id FROM project_members
 UNION SELECT id,pm_id FROM projects WHERE pm_id IS NOT NULL
) x ON x.project_id=p.id WHERE p.status_code IN ('STAGE_EXEC','STAGE_PROPOSAL');
CREATE TABLE evaluation_plans (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 created_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_on timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
 employee_id bigint NOT NULL REFERENCES employees(id),
 project_id bigint REFERENCES projects(id),
 assignment_id bigint,
 reviewer_id bigint NOT NULL REFERENCES employees(id),
 approved_by bigint REFERENCES employees(id),
 kind varchar(20) NOT NULL,
 state varchar(40) NOT NULL,
 title varchar(250) NOT NULL,
 start_date date NOT NULL,
 end_date date NOT NULL,
 goals_json text NOT NULL,
 planned_mm_json text NOT NULL,
 actual_mm_json text NOT NULL DEFAULT '{}',
 results_json text NOT NULL DEFAULT '[]',
 review_comment text NOT NULL DEFAULT '',
 result_comment text NOT NULL DEFAULT '',
 approved_on timestamptz,
 evaluated_on timestamptz,
 goals_hash varchar(64),
 score double precision,
 CONSTRAINT evaluation_plan_period CHECK(end_date >= start_date),
 CONSTRAINT evaluation_plan_scope CHECK ((kind='PROJECT' AND project_id IS NOT NULL AND assignment_id IS NOT NULL) OR (kind='POOL' AND project_id IS NULL AND assignment_id IS NULL)),
 CONSTRAINT evaluation_plan_state CHECK(state IN ('DRAFT','SUBMITTED','REVISION_REQUIRED','APPROVED','RESULT_REVISION_REQUIRED','RESULT_SUBMITTED','EVALUATED')),
 CONSTRAINT evaluation_plan_reviewer CHECK(reviewer_id<>employee_id),
 CONSTRAINT evaluation_plan_assignment FOREIGN KEY(assignment_id,project_id,employee_id) REFERENCES evaluation_assignments(id,project_id,employee_id),
 CONSTRAINT evaluation_plan_score CHECK(score IS NULL OR (score >= 0 AND score <= 100))
);
CREATE INDEX evaluation_plan_employee ON evaluation_plans(employee_id,start_date);
CREATE INDEX evaluation_plan_project ON evaluation_plans(project_id,state);
