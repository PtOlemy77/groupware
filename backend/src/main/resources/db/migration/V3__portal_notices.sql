-- Add portal content without modifying existing employees or business records.
CREATE TABLE portal_notices (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title varchar(200) NOT NULL CHECK (char_length(trim(title)) BETWEEN 1 AND 200),
  content text NOT NULL CHECK (char_length(trim(content)) BETWEEN 1 AND 20000),
  published boolean NOT NULL DEFAULT false,
  pinned boolean NOT NULL DEFAULT false,
  created_by_id bigint NOT NULL REFERENCES employees(id),
  version bigint NOT NULL DEFAULT 0,
  created_on timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_on timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_portal_notices_public_order ON portal_notices(published, pinned DESC, created_on DESC, id DESC);
